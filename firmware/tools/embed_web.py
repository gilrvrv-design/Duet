"""Embed the web app (firmware/web/) in the firmware as gzipped byte arrays.

    python3 tools/embed_web.py <web dir> <output header>

The header defines duet::kWebAssets (duet_web.hpp). index.html is served at "/". The
output is rewritten only when it changes, so an unchanged app does not rebuild.
"""

import gzip
import sys
from pathlib import Path

TYPES = {
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".svg": "image/svg+xml",
}


def embed(web: Path) -> str:
    files = sorted(p for p in web.iterdir() if p.suffix in TYPES)
    lines = [
        "// Generated by tools/embed_web.py from firmware/web/; do not edit.",
        "#pragma once",
        '#include "duet_web.hpp"',
        "",
        "namespace duet {",
        "",
    ]
    entries = []
    for i, path in enumerate(files):
        data = gzip.compress(path.read_bytes(), compresslevel=9, mtime=0)
        rows = (", ".join(str(b) for b in data[k : k + 24]) for k in range(0, len(data), 24))
        lines += [f"inline constexpr unsigned char kWebAsset{i}[] = {{"]
        lines += [f"    {row}," for row in rows]
        lines += ["};", ""]
        url = "/" if path.name == "index.html" else f"/{path.name}"
        entries.append(f'    {{"{url}", "{TYPES[path.suffix]}", kWebAsset{i}, {len(data)}}},')
    lines += [
        "inline constexpr WebAsset kWebAssets[] = {",
        *entries,
        "};",
        "",
        "}  // namespace duet",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    web, out = Path(sys.argv[1]), Path(sys.argv[2])
    header = embed(web)
    if not out.is_file() or out.read_text() != header:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(header)


if __name__ == "__main__":
    main()
