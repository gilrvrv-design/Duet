"""Compile the instruments the planner plans for into the firmware, from the Hub's own
instrument files, read and checked by the Hub's own loader (defaults included):

    python3 tools/embed_instruments.py <profiles dir> <output header>

The header is committed (lib/duet_core/src/duet_instrument_data.hpp), so building the
firmware needs no Python packages: `make -C firmware instruments` regenerates it, and a
test fails while it is out of date.

The header defines duet::kCarriageInstruments (every instrument a carriage-striker bot
plays) and duet::kKeyboardInstruments (every keyboard a person plays by an LED strip),
as duet_instruments.hpp describes them. The output is rewritten only when it changes.
"""

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))  # the Hub's package

from duet.instruments import SCHEMA, CarriageStriker, Instrument, LedStrip, parse_instrument  # noqa: E402


def number(value: float) -> str:
    """A float as Python writes it: the shortest text that reads back as the same double,
    which C++ reads back the same way too."""
    return repr(float(value))


def carriage(inst: Instrument, notes: str) -> list[str]:
    bot = inst.bot
    kin, striker = bot.kinematics, bot.striker
    return [
        f'    {{"{inst.id}", {notes}, {len(inst.notes)}, {number(inst.tolerance_cents)},',
        f"     {number(kin.steps_per_mm)}, {number(kin.v_max_mm_s)}, "
        f"{number(kin.a_max_mm_s2)}, {number(kin.settle_ms)},",
        f'     "{number(kin.v_max_mm_s)}", "{number(kin.a_max_mm_s2)}",',
        f"     {striker.pulse_us[0]}, {striker.pulse_us[1]}, {number(striker.recovery_ms)}, "
        f"{number(striker.latency_ms)}, {number(striker.duty_limit)}, "
        f"{number(striker.duty_window_s)}}},",
    ]


def embed(profiles: Path) -> str:
    instruments = []
    for path in sorted(profiles.glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        if isinstance(data, dict) and data.get("schema") == SCHEMA:
            instruments.append(parse_instrument(data))
    lines = [
        "// Generated by tools/embed_instruments.py from src/duet/profiles/; do not edit.",
        "// After changing an instrument file: make -C firmware instruments",
        "#pragma once",
        '#include "duet_instruments.hpp"',
        "",
        "namespace duet {",
        "",
    ]
    carriages, keyboards = [], []
    for i, inst in enumerate(instruments):
        if isinstance(inst.bot, CarriageStriker):
            notes = f"kCarriageNotes{i}"
            lines.append(f"inline constexpr CarriageNote {notes}[] = {{")
            lines += [
                f"    {{{n.midi}, {number(n.sounding_hz)}, {steps}}},"
                for n, steps in zip(inst.notes, inst.bot.positions, strict=True)
            ]
            lines += ["};", ""]
            carriages += carriage(inst, notes)
        if inst.range is not None and inst.human and isinstance(inst.human.guide, LedStrip):
            led = inst.human.guide
            keyboards.append(
                f'    {{"{inst.id}", {inst.range[0]}, {inst.range[1]}, {number(led.leds_per_m)}, '
                f"{number(led.white_key_mm)}, {number(led.first_led_mm)}}},"
            )
    lines += ["inline constexpr CarriageInstrument kCarriageInstruments[] = {", *carriages, "};"]
    lines += ["", "inline constexpr KeyboardInstrument kKeyboardInstruments[] = {", *keyboards]
    lines += ["};", "", "}  // namespace duet"]
    return "\n".join(lines) + "\n"


def main() -> None:
    profiles, out = Path(sys.argv[1]), Path(sys.argv[2])
    header = embed(profiles)
    if not out.is_file() or out.read_text() != header:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(header)


if __name__ == "__main__":
    main()
